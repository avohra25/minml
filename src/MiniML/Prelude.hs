-- | The standard prelude, written in MiniML itself and type-checked at
-- start-up like any user program.
module MiniML.Prelude (preludeSource) where

preludeSource :: String
preludeSource = unlines
  [ "let id x = x"
  , "let const x _ = x"
  , "let compose f g x = f (g x)"
  , "let flip f x y = f y x"
  , "let abs n = if n < 0 then 0 - n else n"
  , "let max a b = if a >= b then a else b"
  , "let min a b = if a <= b then a else b"
  , "let rec length xs = match xs with [] -> 0 | _ :: t -> 1 + length t"
  , "let hd xs = match xs with x :: _ -> x | [] -> failwith \"hd: empty list\""
  , "let tl xs = match xs with _ :: t -> t | [] -> failwith \"tl: empty list\""
  , "let rec nth xs n = match xs with"
  , "  | [] -> failwith \"nth: index out of range\""
  , "  | x :: t -> if n = 0 then x else nth t (n - 1)"
  , "let rec map f xs = match xs with [] -> [] | x :: t -> f x :: map f t"
  , "let rec filter p xs = match xs with"
  , "  | [] -> []"
  , "  | x :: t -> if p x then x :: filter p t else filter p t"
  , "let rec foldl f acc xs = match xs with [] -> acc | x :: t -> foldl f (f acc x) t"
  , "let rec foldr f xs acc = match xs with [] -> acc | x :: t -> f x (foldr f t acc)"
  , "let rev xs = foldl (fun acc x -> x :: acc) [] xs"
  , "let rec range a b = if a >= b then [] else a :: range (a + 1) b"
  , "let sum xs = foldl (fun a b -> a + b) 0 xs"
  , "let rec exists p xs = match xs with [] -> false | x :: t -> p x || exists p t"
  , "let rec for_all p xs = match xs with [] -> true | x :: t -> p x && for_all p t"
  , "let mem x xs = exists (fun y -> y = x) xs"
  , "let rec zip xs ys = match (xs, ys) with"
  , "  | (x :: xt, y :: yt) -> (x, y) :: zip xt yt"
  , "  | _ -> []"
  , "let concat xss = foldr (fun xs acc -> xs @ acc) xss []"
  , "let concat_map f xs = concat (map f xs)"
  , "let rec assoc k kvs = match kvs with"
  , "  | [] -> failwith \"assoc: key not found\""
  , "  | (k2, v) :: t -> if k = k2 then v else assoc k t"
  , "let rec iterate n f x = if n <= 0 then x else iterate (n - 1) f (f x)"
  , "let rec string_concat sep xs = match xs with"
  , "  | [] -> \"\""
  , "  | [x] -> x"
  , "  | x :: t -> x ^ sep ^ string_concat sep t"
  ]
